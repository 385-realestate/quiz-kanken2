// ── 生成処理 ────────────────────────────────────────────────────
const questions = [];
let seq = 0;
function push(category, categoryLabel, tag, prompt, answer, meaning, example, explanation, choices) {
  seq += 1;
  questions.push({
    id: `${category}-${String(seq).padStart(3, '0')}`,
    category,
    categoryLabel,
    prompt,
    answer,
    meaning,
    example,
    explanation: explanation || '',
    choices: choices || [],
    source: 'original',
    tags: [tag || categoryLabel],
    difficulty: 2,
  });
}

