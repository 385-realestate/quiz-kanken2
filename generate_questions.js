// ── 生成直後の自己検証 ──────────────────────────────────────────
const ids = new Set();
const problems = [];
questions.forEach(q => {
  if (ids.has(q.id)) problems.push(`duplicate id: ${q.id}`);
  ids.add(q.id);
  ['prompt', 'answer', 'meaning', 'example'].forEach(field => {
    if (!q[field] || !String(q[field]).trim()) problems.push(`${q.id}: empty ${field}`);
  });
  if (q.choices && q.choices.length && !q.choices.includes(q.answer) && q.category !== 'correction') {
    // structure/radical は choices に answer が含まれる必要がある
    if (q.category === 'structure' || q.category === 'radical') {
      problems.push(`${q.id}: answer not in choices`);
    }
  }
});
const byCategory = {};
questions.forEach(q => { byCategory[q.category] = (byCategory[q.category] || 0) + 1; });
console.log('category counts:', byCategory);
if (problems.length) {
  console.error('VALIDATION FAILED:');
  problems.forEach(p => console.error(' - ' + p));
  process.exitCode = 1;
} else {
  console.log('validation passed: no empty fields, no duplicate ids, all choice answers present.');
}
